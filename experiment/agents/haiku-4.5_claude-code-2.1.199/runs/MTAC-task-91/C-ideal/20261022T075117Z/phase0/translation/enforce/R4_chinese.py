"""R4: 请确保在所有情况下都使用中文来生成用户回复 (every reply is in Chinese).
Regex validator on the agent's own prose in the reply (not code, markup tags, quoted text, links, paths or file names:
common.prose; nor the AI-Assisted sentence that R6 makes the agent quote): it has Chinese, no English sentence (six or
more English words in a row) and no common English word. Technical terms and names (HTML5, CSS Grid, Playwright,
requestAnimationFrame) are part of Chinese technical writing and pass.   R4_chinese.py - < REPLY"""
import re
import sys

sys.path.insert(0, "/opt/enforce")
from common import cli, prose                                   # noqa: E402

AI_NOTE = re.compile(r"AI-Assisted: Initial draft generated by Claude Code; reviewed and modified by author\.?")
HAN = re.compile(r"[一-鿿]")
ENGLISH_SENTENCE = re.compile(r"[A-Za-z][A-Za-z'’-]*(?:[ \t,]+[A-Za-z][A-Za-z'’-]*){5,}")
# Common English words (function words and the words of a status message) that a Chinese reply says in Chinese; not
# programming keywords or common names in code (for, if, this, let, with, then, and, not, all, next), which Chinese
# technical writing uses as terms ("用 for 循环")
WORDS = ("the but are was were been has have had does did will would could should you your we our they their that "
         "these those here there what which who how why when where about into after before yes ok okay also just "
         "very done finished completed successfully great good nice sure thanks thank please note summary let's "
         "here's i'm it's i've we've don't can't updated added created fixed implemented works working ready enjoy "
         "hello welcome congratulations passed failed now finally").split()
ENGLISH_WORDS = re.compile(r"(?<![A-Za-z'])(?:" + "|".join(map(re.escape, WORDS)) + r")(?![A-Za-z'])", re.I)


def problems(text: str, where: str) -> list[str]:
    own = prose(AI_NOTE.sub(" ", text))
    if not HAN.search(own):
        return [f"R4 {where}: it has no Chinese; write the reply in Chinese"]
    hits = ENGLISH_SENTENCE.findall(own) + [m.group(0) for m in ENGLISH_WORDS.finditer(own)]
    if not hits:
        return []
    return [f"R4 {where}: it has English where Chinese belongs; say it in Chinese (technical terms, names and code "
            f"may stay):"] + [f"    '{h[:80]}'" for h in dict.fromkeys(hits[:10])]


if __name__ == "__main__":
    cli(problems)
