"""R4: 请确保在所有情况下都使用中文来生成用户回复 (every reply is in Chinese).
Regex validator on the reply's prose: it has Chinese, and no English sentence (six or more English words in a row).
Code (fenced or inline), links and paths are not prose; nor is the AI-Assisted line that R6 makes the agent quote.
R4_chinese.py - < REPLY"""
import re
import sys

sys.path.insert(0, "/opt/enforce")
from common import cli                                          # noqa: E402

NOT_PROSE = re.compile(r"```.*?(?:```|\Z)|`[^`\n]*`|https?://\S+|(?:\.{0,2}/)?[A-Za-z0-9_.-]+(?:/[A-Za-z0-9_.-]+)+|"
                       r"AI-Assisted: Initial draft generated by Claude Code; reviewed and modified by author\.?",
                       re.S)
HAN = re.compile(r"[一-鿿]")
ENGLISH_SENTENCE = re.compile(r"[A-Za-z][A-Za-z'’-]*(?:[ \t,]+[A-Za-z][A-Za-z'’-]*){5,}")


def problems(text: str, where: str) -> list[str]:
    prose = NOT_PROSE.sub(" ", text)
    if not HAN.search(prose):
        return [f"R4 {where}: it has no Chinese; write the reply in Chinese"]
    hits = ENGLISH_SENTENCE.findall(prose)
    if not hits:
        return []
    return [f"R4 {where}: it has English sentences; write them in Chinese (code and names may stay in `code`):"] + \
           [f"    '{h[:80]}'" for h in hits[:8]]


if __name__ == "__main__":
    cli(problems)
