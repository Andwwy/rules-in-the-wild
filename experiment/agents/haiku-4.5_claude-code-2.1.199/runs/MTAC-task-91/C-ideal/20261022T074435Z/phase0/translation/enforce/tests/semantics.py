def hook(name: str, event: dict) -> dict | None:
    done = subprocess.run(["/usr/bin/python3", "-I", f"/opt/enforce/hooks/{name}"], input=json.dumps(event),
                          capture_output=True, text=True, cwd="/workspace")
    if done.returncode:
        raise RuntimeError(f"{name}: exit {done.returncode}: {done.stderr[-400:]}")
    return json.loads(done.stdout) if done.stdout.strip() else None


def hook_cases(d: str) -> list[tuple[str, bool, bool]]:
    """(case, flagged, must flag) for each hook, in a scratch folder under /workspace (d)."""
    out, good = [], JS_HEAD + js_fn(10)
    w = lambda path, content: {"hook_event_name": "PreToolUse", "tool_name": "Write",          # noqa: E731
                               "tool_input": {"file_path": path, "content": content}}
    out.append(("before Write: a conforming file", bool(hook("before_write.py", w(f"{d}/a.js", good))), False))
    out.append(("before Write: no coding line", bool(hook("before_write.py", w(f"{d}/a.js", js_fn(10)))), True))
    out.append(("before Write: a 61-line function", bool(hook("before_write.py", w(f"{d}/a.js", JS_HEAD + js_fn(61)))), True))
    out.append(("before Write: a Markdown file", bool(hook("before_write.py", w(f"{d}/notes.md", "# notes\n"))), False))
    with open(f"{d}/a.js", "w") as f:
        f.write(good)
    edit = lambda old, new: {"hook_event_name": "PreToolUse", "tool_name": "Edit",               # noqa: E731
                             "tool_input": {"file_path": f"{d}/a.js", "old_string": old, "new_string": new}}
    out.append(("before Edit: keeps the file conforming", bool(hook("before_write.py", edit("let v1 = 1;", "let v1 = 2;"))), False))
    out.append(("before Edit: removes the coding line", bool(hook("before_write.py", edit("// -*- coding: utf-8 -*-\n", ""))), True))
    bash = {"hook_event_name": "PostToolUse", "tool_name": "Bash", "tool_input": {"command": "printf ..."}, "tool_response": {}}
    out.append(("after Bash: nothing breaks a rule", bool(hook("after_bash.py", bash)), False))
    with open(f"{d}/shell.js", "w") as f:                       # what a shell command writes
        f.write(js_fn(5))
    out.append(("after Bash: a file without its header lines", bool(hook("after_bash.py", bash)), True))
    stop = lambda reply: {"hook_event_name": "Stop", "stop_hook_active": False, "last_assistant_message": reply,  # noqa: E731
                          "transcript_path": "/nonexistent"}
    r = hook("end_of_turn.py", stop(OK_REPLY))
    out.append(("Stop: the shell-written file is still there", bool(r) and "R5" in r["reason"] and "R6" in r["reason"], True))
    os.unlink(f"{d}/shell.js")
    out.append(("Stop: a conforming reply and files", bool(hook("end_of_turn.py", stop(OK_REPLY))), False))
    out.append(("Stop: a reply that breaks R1 and R8", bool(hook("end_of_turn.py", stop("代码小灵完成了"))), True))
    return out


def main() -> int:
    wrong = 0
    for name, content, must, why in KINDS:
        got = is_code(name, content)
        wrong += got != must
        print(f"{'ok   ' if got == must else 'WRONG'} code file? {name}: {why} ({got})")
    for rule, text, must, why in REPLY:
        got = bool(rule.problems(text, "the reply"))
        wrong += got != must
        print(f"{'ok   ' if got == must else 'WRONG'} {rule.__name__[:2]} reply: {why} (flagged: {got})")
    for rule, name, content, must, why in FILES:
        if rule is R7_function_length:
            got = bool(rule.check([(name, content)]))
        else:
            got = bool(rule.problems(content, name))
        wrong += got != must
        print(f"{'ok   ' if got == must else 'WRONG'} {rule.__name__[:2]} {name}: {why} (flagged: {got})")
    with tempfile.TemporaryDirectory(dir="/workspace") as d:
        os.chmod(d, 0o755)
        for case, got, must in hook_cases(d):
            wrong += got != must
            print(f"{'ok   ' if got == must else 'WRONG'} hook {case} (flagged: {got})")
    print(f"{len(KINDS) + len(REPLY) + len(FILES)} check cases and the hook cases: {wrong} wrong")
    return 1 if wrong else 0


if __name__ == "__main__":
    sys.exit(main())
