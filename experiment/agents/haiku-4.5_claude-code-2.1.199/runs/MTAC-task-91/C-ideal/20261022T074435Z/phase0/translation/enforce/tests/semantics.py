def body(n: int, indent: str = "    ") -> str:
    return "".join(f"{indent}let v{i} = {i};\n" for i in range(n))


def js_fn(lines: int) -> str:                       # a function of exactly `lines` lines
    return "function f() {\n" + body(lines - 2) + "}\n"


