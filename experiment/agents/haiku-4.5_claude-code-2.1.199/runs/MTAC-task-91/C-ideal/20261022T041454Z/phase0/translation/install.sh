#!/bin/bash
# The hand-made phase 0 of C-ideal, run as root after its files are in /opt/enforce (runner.py): the tools that the
# routes name (the toolbox's recipes), then the agent's Claude Code settings in the project scope of /workspace, which
# the agent cannot change (the folder and the file are root's; the file is immutable).
set -euo pipefail
enforce install git pre-commit semgrep
chown -R root:root /opt/enforce && chmod -R a+rX,go-w /opt/enforce
mkdir -p /workspace/.claude
install -o root -g root -m 0644 /opt/enforce/settings.json /workspace/.claude/settings.json
chown root:root /workspace/.claude && chmod 0755 /workspace/.claude
chattr +i /workspace/.claude/settings.json
# the checks as the agent will run them: each must pass on a conforming file and refuse a breaking one
cd /tmp && rm -rf enforce-smoke && mkdir enforce-smoke && cd enforce-smoke
printf '// -*- coding: utf-8 -*-\n// AI-Assisted: Initial draft generated by Claude Code; reviewed and modified by author.\nfunction ok() {\n    return 1;\n}\n' > ok.js
printf 'function bad() {\n    return 1;\n}\n' > bad.js
chmod a+r ok.js bad.js
runuser -u agent -- /usr/bin/python3 -I /opt/enforce/R5_coding_line.py ok.js
runuser -u agent -- /usr/bin/python3 -I /opt/enforce/R6_ai_note.py ok.js
runuser -u agent -- /usr/bin/python3 -I /opt/enforce/R7_function_length.py ok.js
! runuser -u agent -- /usr/bin/python3 -I /opt/enforce/R5_coding_line.py bad.js 2>/dev/null
! runuser -u agent -- /usr/bin/python3 -I /opt/enforce/R6_ai_note.py bad.js 2>/dev/null
cd /tmp && rm -rf enforce-smoke
echo "phase 0 (C-ideal): installed"
